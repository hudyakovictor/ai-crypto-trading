import { NextResponse } from "next/server";

export const dynamic = "force-dynamic";

/**
 * СИДИНГ ДЕМО-ИСТОРИИ УДАЛЁН (410 Gone).
 *
 * Прежний POST /api/research/seed:
 *  - записывал в `assets` выдуманные цены (BTC 78 000, ETH 2 450 …) и в
 *    `forecasts` — 22 «исторических» прогноза с заранее проставленными
 *    исходами (17 hit / 5 miss), то есть подделывал бумажный журнал;
 *  - затем прогонял эту фиктивную историю через обучение весов, поэтому
 *    лаборатория с первой минуты «знала» win-rate, которого никогда не было;
 *  - вызывался автоматически из UI при первом открытии и не требовал ни
 *    подтверждения, ни аутентификации;
 *  - не имел маркера «это демо-данные», поэтому отличить seeded-строки от
 *    настоящих исходов было невозможно.
 *
 * Система задумана как честный журнал: прогноз фиксируется на живых котировках
 * и проверяется через 15 минут реальными котировками. Поэтому демо-истории здесь
 * больше нет — журнал наполняется только циклами планировщика.
 */
export async function POST() {
  return NextResponse.json(
    {
      success: false,
      error: "gone",
      message:
        "Сидинг демо-истории удалён: бумажный журнал должен содержать только реальные прогнозы и их реальные исходы. Запустите цикл — POST /api/research/cycle.",
    },
    { status: 410 }
  );
}

export async function GET() {
  return POST();
}
